class CTBrainDataset(Dataset):
    def __init__(self, image_paths, mask_paths, transform=None):
        self.image_paths = image_paths
        self.mask_paths = mask_paths
        self.transform = transform

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_input = self.image_paths[idx]
        mask_input = self.mask_paths[idx]

        # Load image
        if isinstance(img_input, str):
            image = cv2.imread(img_input, cv2.IMREAD_GRAYSCALE)
        else:
            image = img_input.astype(np.uint8)

        # Load mask
        if isinstance(mask_input, str):
            mask = cv2.imread(mask_input, cv2.IMREAD_GRAYSCALE)
        else:
            mask = mask_input.astype(np.uint8)

        # Apply transform (Albumentations returns channel-last by default)
        if self.transform:
            augmented = self.transform(image=image, mask=mask)
            image = augmented['image']
            mask = augmented['mask']

            # Ensure mask has shape [1, H, W]
            if mask.ndim == 3 and mask.shape[0] != 1:
                mask = mask.permute(2, 0, 1)  # Convert from [H, W, 1] to [1, H, W]
        else:
            image = torch.tensor(image, dtype=torch.float32) / 255.0
            mask = torch.tensor(mask, dtype=torch.float32) / 255.0
            image = image.unsqueeze(0)  # [1, H, W]
            mask = mask.unsqueeze(0)    # [1, H, W]

        # Binarize mask
        mask = (mask > 0).float()

        return image, mask


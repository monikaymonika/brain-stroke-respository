class PatchSegmentationDataset(Dataset):
    def __init__(self, images, masks, patch_size=128, positive_prob=0.5):
        self.images = images
        self.masks = masks
        self.patch_size = patch_size
        self.positive_prob = positive_prob  # % of patches from positive areas

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        img = self.images[idx]
        mask = self.masks[idx]

        h, w = mask.shape[:2]

        if random.random() < self.positive_prob and mask.sum() > 0:
            # Sample from region with positives
            ys, xs = mask.squeeze().nonzero()
            center_y = int(random.choice(ys))
            center_x = int(random.choice(xs))
        else:
            # Random crop anywhere
            center_y = random.randint(0, h-1)
            center_x = random.randint(0, w-1)

        # Compute crop bounds
        half = self.patch_size // 2
        y1 = max(center_y - half, 0)
        y2 = min(center_y + half, h)
        x1 = max(center_x - half, 0)
        x2 = min(center_x + half, w)

        # Pad if crop smaller than patch
        pad_y = self.patch_size - (y2 - y1)
        pad_x = self.patch_size - (x2 - x1)

        img_crop = img[y1:y2, x1:x2]
        mask_crop = mask[y1:y2, x1:x2]

        if pad_y > 0 or pad_x > 0:
            img_crop = np.pad(img_crop, ((0, pad_y), (0, pad_x), (0,0)), mode='constant')
            mask_crop = np.pad(mask_crop, ((0, pad_y), (0, pad_x), (0,0)), mode='constant')

        # Convert to tensors
        img_crop = torch.tensor(img_crop.transpose(2,0,1), dtype=torch.float32)
        mask_crop = torch.tensor(mask_crop.transpose(2,0,1), dtype=torch.float32)

        return img_crop, mask_crop

